function seededRandom(seed) {
  let s = seed;
  return () => {
    s = (Math.imul(1664525, s) + 1013904223) | 0;
    return (s >>> 0) / 0xffffffff;
  };
}

function hashCode(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (Math.imul(31, h) + str.charCodeAt(i)) | 0;
  }
  return h;
}

const shuffleCache = new Map();

export function getQuestionForRound(roomId, roundNumber) {
  if (!shuffleCache.has(roomId)) {
    const arr = [...QUESTIONS];
    const rand = seededRandom(Math.abs(hashCode(roomId)));
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    shuffleCache.set(roomId, arr);
  }
  return shuffleCache.get(roomId)[roundNumber % QUESTIONS.length];
}
