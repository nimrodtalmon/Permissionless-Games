// ─── Seeded shuffle (Fisher-Yates) ────────────────────────────────────────────
// Shuffles the word list once per room using the roomId as a seed.
// Round N then picks index N % length — guaranteeing every word appears
// before any repeats, no matter how many rounds are played.

function seededRandom(seed) {
  // LCG — fast, good enough for shuffling a word list
  let s = seed;
  return () => {
    s = (Math.imul(1664525, s) + 1013904223) | 0;
    return (s >>> 0) / 0xffffffff;
  };
}

function hashCode(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (Math.imul(31, h) + str.charCodeAt(i)) | 0;
  }
  return h;
}

function shuffleForRoom(roomId) {
  const arr = [...WORDS];
  const rand = seededRandom(Math.abs(hashCode(roomId)));
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Cache the shuffled list per room so repeated calls don't re-shuffle
const shuffleCache = new Map();

export function getWordForRound(roomId, roundNumber) {
  if (!shuffleCache.has(roomId)) {
    shuffleCache.set(roomId, shuffleForRoom(roomId));
  }
  const list = shuffleCache.get(roomId);
  return list[roundNumber % list.length];
}
